import logging

from odoo import api, fields, models, _

_logger = logging.getLogger(__name__)


class CorrSfgMassTagWizard(models.TransientModel):
    _name = "corr.sfg.mass.tag.wizard"
    _description = "Mass Tag SFG Products"

    apply_role = fields.Selection(
        [
            ("raw_material", "Raw Material"),
            ("sfg", "Semi-finished"),
            ("finished_good", "Finished Good"),
            ("other", "Other / Unclassified"),
        ],
        string="Target Product Role",
        required=True,
        default="sfg",
    )
    only_corr_sfg_key = fields.Boolean(
        string="Only staged SFGs (corr_sfg_key set)",
        default=True,
        help=(
            "When enabled, only products with a corr_sfg_key (staged SFGs generated by the corrugation bridge) "
            "are affected."
        ),
    )
    name_contains = fields.Char(
        string="Name contains",
        help="Optional name filter (case-insensitive). Leave empty to ignore.",
    )
    has_bom = fields.Boolean(
        string="Has BoM",
        help="When enabled, only tag products that have at least one Bill of Materials.",
        default=False,
    )
    active_only = fields.Boolean(
        string="Active products only",
        default=True,
    )
    preview_count = fields.Integer(string="Matched Products", readonly=True)
    preview_domain = fields.Char(string="Last Domain", readonly=True)
    log_message = fields.Text(string="Log", readonly=True)

    def _candidate_domain(self):
        self.ensure_one()
        domain = []
        ProductTemplate = self.env["product.template"]
        if self.only_corr_sfg_key and "corr_sfg_key" in ProductTemplate._fields:
            domain.append(("corr_sfg_key", "!=", False))
        if self.name_contains:
            name = (self.name_contains or "").strip()
            if name:
                domain.append(("name", "ilike", name))
        if self.has_bom and "bom_ids" in ProductTemplate._fields:
            domain.append(("bom_ids", "!=", False))
        if self.active_only:
            domain.append(("active", "=", True))
        return domain

    def action_preview(self):
        self.ensure_one()
        ProductTemplate = self.env["product.template"].with_context(active_test=not self.active_only)
        domain = self._candidate_domain()
        count = ProductTemplate.search_count(domain)
        self.preview_count = count
        self.preview_domain = str(domain)
        self.log_message = _("%s product template(s) match the current filters.") % count
        _logger.info(
            "corr_sfg_mass_tag preview: %s templates match domain %s",
            count,
            domain,
        )
        return {
            "type": "ir.actions.act_window",
            "res_model": self._name,
            "view_mode": "form",
            "res_id": self.id,
            "target": "new",
        }

    def action_apply(self):
        self.ensure_one()
        ProductTemplate = self.env["product.template"].with_context(active_test=not self.active_only)
        domain = self._candidate_domain()
        products = ProductTemplate.search(domain)
        if not products:
            msg = _("No products matched the filters; nothing was updated.")
            self.log_message = msg
            _logger.info("corr_sfg_mass_tag apply: %s", msg)
            self.preview_count = 0
            self.preview_domain = str(domain)
            return self.action_preview()

        products.write({"product_role": self.apply_role})
        msg = _(
            "Updated %(count)s product template(s) to role '%(role)s'.",
            count=len(products),
            role=dict(self._fields["apply_role"].selection).get(self.apply_role, self.apply_role),
        )
        self.log_message = msg
        self.preview_count = len(products)
        self.preview_domain = str(domain)
        _logger.info(
            "corr_sfg_mass_tag apply: %s templates updated to role=%s using domain=%s",
            len(products),
            self.apply_role,
            domain,
        )
        return self.action_preview()

