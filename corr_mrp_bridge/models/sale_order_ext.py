from odoo import api, models


class SaleOrder(models.Model):
    _inherit = "sale.order"

    def _corr_show_all_chained_mos_enabled(self):
        return self.env["ir.config_parameter"].sudo().get_param(
            "corr_mrp_bridge.show_all_chained_mos_in_so_smart_button",
            default="0",
        ) in ("1", "true", "True")

    def _corr_keep_so_created_corr_mos_draft_enabled(self):
        return self.env["ir.config_parameter"].sudo().get_param(
            "corr_mrp_bridge.keep_so_created_corr_mos_draft",
            default="0",
        ) in ("1", "true", "True")

    def _corr_is_staged_sale_mo_root(self, productions):
        return bool(
            productions.filtered(
                lambda mo: mo.bom_id.corr_spec_id
                or mo.bom_id.corr_stage
                or mo.product_id.product_tmpl_id.corr_sfg_key
            )
        )

    def _corr_collect_recursive_children(self, roots):
        Production = self.env["mrp.production"]
        seen = roots
        frontier = roots
        while frontier:
            children = Production
            for production in frontier:
                children |= production._get_children()
            children -= seen
            if not children:
                break
            seen |= children
            frontier = children
        return seen

    def _corr_action_view_mrp_production_list(self):
        self.ensure_one()
        return {
            "name": f"Manufacturing Orders Generated by {self.name}",
            "res_model": "mrp.production",
            "type": "ir.actions.act_window",
            "domain": [("id", "in", self.mrp_production_ids.ids)],
            "view_mode": "list,form",
            "context": {
                "corr_reopen_so_mrp_after_confirm": True,
                "corr_sale_order_id": self.id,
            },
        }

    @api.depends("procurement_group_id.stock_move_ids.created_production_id.procurement_group_id.mrp_production_ids")
    def _compute_mrp_production_ids(self):
        super()._compute_mrp_production_ids()
        if not self._corr_show_all_chained_mos_enabled():
            return
        for sale in self:
            base_mos = sale.mrp_production_ids
            if not base_mos or not sale._corr_is_staged_sale_mo_root(base_mos):
                continue
            expanded_mos = sale._corr_collect_recursive_children(base_mos)
            sale.mrp_production_ids = expanded_mos
            sale.mrp_production_count = len(expanded_mos)

    def action_view_mrp_production(self):
        self.ensure_one()
        productions = self.mrp_production_ids
        if (
            self._corr_keep_so_created_corr_mos_draft_enabled()
            and len(productions) == 1
            and productions.state == "draft"
        ):
            return self._corr_action_view_mrp_production_list()
        return super().action_view_mrp_production()
